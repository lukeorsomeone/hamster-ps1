"""Converts the Godot game's bitmap font (font_psx_v2.fnt/.png) into a PS1 4-bit
texture + glyph table: src/font_psx.h.

    python tools/make_font.py path/to/font_psx_v2.fnt src/font_psx.h

Glyphs are repacked into a 256x32 atlas (one PS1 texture page wide).
Colour 0 of the palette is fully transparent on the PS1.
"""
import re, sys, os
from PIL import Image

ATLAS_W, ATLAS_H = 256, 32

def main(fnt_path, out_path):
    chars = {}
    page = None
    for line in open(fnt_path):
        m = re.match(r'page id=0 file="([^"]+)"', line)
        if m: page = m.group(1)
        m = re.match(r'char id=(\d+) x=(\d+) y=(\d+) width=(\d+) height=(\d+) '
                     r'xoffset=(-?\d+) yoffset=(-?\d+) xadvance=(\d+)', line)
        if m:
            v = list(map(int, m.groups()))
            chars[v[0]] = v[1:]
    img = Image.open(os.path.join(os.path.dirname(fnt_path), page)).convert('RGBA')

    # palette: transparent first, then every opaque colour in the image
    palette = [None]
    pix = img.load()
    for y in range(img.height):
        for x in range(img.width):
            c = pix[x, y]
            if c[3] >= 128 and c[:3] not in palette:
                palette.append(c[:3])
    assert len(palette) <= 16, 'too many colours for 4-bit'

    atlas = [[0] * ATLAS_W for _ in range(ATLAS_H)]
    placed = {}            # (x, y, w, h) in source -> (u, v)
    cx, cy, row_h = 0, 0, 0
    glyphs = {}
    for code in range(32, 128):
        if code not in chars:
            continue
        x, y, w, h, xo, yo, adv = chars[code]
        key = (x, y, w, h)
        if key not in placed:
            if cx + w > ATLAS_W:
                cx, cy, row_h = 0, cy + row_h, 0
            assert cy + h <= ATLAS_H, 'atlas full'
            for j in range(h):
                for i in range(w):
                    c = pix[x + i, y + j]
                    atlas[cy + j][cx + i] = palette.index(c[:3]) if c[3] >= 128 else 0
            placed[key] = (cx, cy)
            cx += w
            row_h = max(row_h, h)
        u, v = placed[key]
        glyphs[code] = (u, v, w, h, xo, yo, adv)

    def ps1_colour(c):
        if c is None:
            return 0x0000
        r, g, b = (k >> 3 for k in c)
        v = r | (g << 5) | (b << 10)
        return v if v else 0x8000      # pure black would be transparent: set STP bit

    words = []
    for y in range(ATLAS_H):
        for x in range(0, ATLAS_W, 8):
            w = 0
            for k in range(8):
                w |= atlas[y][x + k] << (4 * k)
            words.append(w)

    with open(out_path, 'w') as f:
        f.write('/* Generated by tools/make_font.py from %s - do not edit */\n' % os.path.basename(fnt_path))
        f.write('#ifndef FONT_PSX_H\n#define FONT_PSX_H\n#include <stdint.h>\n\n')
        f.write('#define FONT_TEX_W %d\n#define FONT_TEX_H %d\n#define FONT_LINE_H 11\n\n' % (ATLAS_W, ATLAS_H))
        f.write('/* u, v, w, h, xoffset, yoffset, xadvance for ASCII 32..127 (w = 0: missing) */\n')
        f.write('static const uint8_t FONT_GLYPH[96][7] = {\n')
        for code in range(32, 128):
            g = glyphs.get(code, (0, 0, 0, 0, 0, 0, 5))
            f.write('\t{%d, %d, %d, %d, %d, %d, %d},  /* %r */\n' % (g + (chr(code),)))
        f.write('};\n\n#ifdef FONT_PSX_PIXELS\n')
        f.write('static const uint16_t FONT_CLUT[16] = {%s};\n\n' %
                ', '.join('0x%04X' % ps1_colour(palette[i] if i < len(palette) else None) for i in range(16)))
        f.write('/* 4 bits per texel, 8 texels per word, low nibble = leftmost */\n')
        f.write('static const uint32_t FONT_TEX[%d] = {\n' % len(words))
        for i in range(0, len(words), 8):
            f.write('\t' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ',\n')
        f.write('};\n#endif\n\n#endif\n')
    print('wrote', out_path, 'glyph cells used:', len(placed), 'palette:', palette)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
